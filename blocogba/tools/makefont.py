glyphs = []
for code in range(32, 96):
    rows = G[chr(code)].split("|")
    assert len(rows) == 7 and all(len(r) == 5 for r in rows), chr(code)
    out = []
    for r in rows:
        v = 0
        for x, c in enumerate(r):
            if c == '#': v |= 1 << x
        out.append(v)
    out.append(0)
    glyphs.append(out)

with open(sys.argv[1], "w") as f:
    f.write("// Gerado por tools/makefont.py - fonte 5x7 propria. 1 bit por pixel, bit 0 = esquerda\n")
    f.write("// Caracteres ASCII 32..95 (so maiusculas)\n")
    f.write("static const unsigned char font8[64][8] = {\n")
    for g in glyphs:
        f.write("    {" + ",".join("0x%02x" % v for v in g) + "},\n")
    f.write("};\n")

if len(sys.argv) > 2:
    from PIL import Image
    prev = Image.new("L", (8 * 32, 16), 0)
    for i, g in enumerate(glyphs):
        for y in range(8):
            for x in range(8):
                if g[y] >> x & 1:
                    prev.putpixel(((i % 32) * 8 + x + 1, (i // 32) * 8 + y), 255)
    prev.resize((8 * 32 * 3, 48), Image.NEAREST).save(sys.argv[2])
